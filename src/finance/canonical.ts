// MARJIN_CANON/1 — the ONE canonical serialization and digest procedure of the Financial Core.
//
// Core/F1 R4: every durable integrity value of the cost history (the review's payload digest, the flag
// audit's deterministic operation identity, the attestation digest) is produced by the trusted writer AND
// recomputed by every strict reader — the server loader, the browser bundle and the page — from the stored
// bytes. One procedure, one result: a reader that cannot recompute the writer's value treats the record as
// corrupt (fail closed). The procedure is PURE and browser-safe (no imports, no I/O, no clock, no binary
// arithmetic beyond 32-bit integer operations of the hash itself).
//
//   canonicalJson(value)  JSON text with every plain object's keys sorted recursively (arrays keep order);
//                         identical to JSON.stringify for scalars and arrays, so numbers / strings / booleans /
//                         null serialize exactly as RTDB stored them.
//   sha256Hex(text)       SHA-256 (FIPS 180-4) of the UTF-8 encoding of `text`, lowercase hex.
//   canonicalDigest(v)    sha256Hex(canonicalJson(v)).
export const CANONICAL_VERSION = "MARJIN_CANON/1";

const isPlainObject = (x: unknown): x is Record<string, unknown> => x !== null && typeof x === "object" && !Array.isArray(x);

/** Deterministic JSON: recursively key-sorted plain objects; arrays in order; JSON.stringify scalar rules. */
export function canonicalJson(value: unknown): string {
  const text = JSON.stringify(value, (_key, v) => {
    if (!isPlainObject(v)) return v;
    const sorted: Record<string, unknown> = {};
    for (const k of Object.keys(v).sort()) sorted[k] = v[k];
    return sorted;
  });
  if (typeof text !== "string") throw new Error("canonicalJson: value is not serializable");
  return text;
}

/** UTF-8 bytes of a JavaScript string (surrogate pairs combined; lone surrogates encoded as U+FFFD). */
export function utf8Bytes(text: string): number[] {
  const out: number[] = [];
  for (let i = 0; i < text.length; i += 1) {
    let cp = text.charCodeAt(i);
    if (cp >= 0xd800 && cp <= 0xdbff && i + 1 < text.length) {
      const lo = text.charCodeAt(i + 1);
      if (lo >= 0xdc00 && lo <= 0xdfff) { cp = 0x10000 + ((cp - 0xd800) << 10) + (lo - 0xdc00); i += 1; }
      else cp = 0xfffd;
    } else if (cp >= 0xd800 && cp <= 0xdfff) cp = 0xfffd;
    if (cp < 0x80) out.push(cp);
    else if (cp < 0x800) out.push(0xc0 | (cp >>> 6), 0x80 | (cp & 0x3f));
    else if (cp < 0x10000) out.push(0xe0 | (cp >>> 12), 0x80 | ((cp >>> 6) & 0x3f), 0x80 | (cp & 0x3f));
    else out.push(0xf0 | (cp >>> 18), 0x80 | ((cp >>> 12) & 0x3f), 0x80 | ((cp >>> 6) & 0x3f), 0x80 | (cp & 0x3f));
  }
  return out;
}

